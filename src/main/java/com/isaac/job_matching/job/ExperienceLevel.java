package com.isaac.job_matching.job;

/**
 * Enum representing the required experience level for a job posting.
 */
public enum ExperienceLevel {
    /** Entry-level / junior position (0-2 years) */
    ENTRY,
    /** Mid-level position (2-5 years) */
    MID,
    /** Senior position (5-8 years) */
    SENIOR,
    /** Lead / principal position (8+ years) */
    LEAD,
    /** Executive / C-level position */
    EXECUTIVE
}
