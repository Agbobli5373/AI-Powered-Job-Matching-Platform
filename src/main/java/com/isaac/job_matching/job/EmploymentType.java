package com.isaac.job_matching.job;

/**
 * Enum representing the type of employment for a job posting.
 */
public enum EmploymentType {
    /** Full-time permanent position */
    FULL_TIME,
    /** Part-time position */
    PART_TIME,
    /** Fixed-term contract */
    CONTRACT,
    /** Internship / training position */
    INTERNSHIP,
    /** Freelance / gig work */
    FREELANCE
}
